#!/usr/bin/env node
"use strict";
/**
 * 生成 js/compiler-core.js：把 compiler/linux/lib 的纯 JS 核心库
 * （hml/css/expr/bundle/png2bin/manifest）打包成浏览器单一命名空间 window.CompilerCore。
 *
 * 不为改动 Linux 端任何源码：核心逻辑单一来源 = compiler/linux/lib。
 * vendor（babel/pako/jszip）在 index.html 里用 <script> 加载，全局注入。
 *
 * 用法：node build-core.js   （生成 compiler/web/js/compiler-core.js）
 */
const fs = require('fs');
const path = require('path');

const LINUX = path.join(__dirname, '..', 'linux', 'lib');
const OUT_FILE = path.join(__dirname, 'js', 'compiler-core.js');
const LIBS = ['expr', 'css', 'hml', 'bundle', 'png2bin', 'manifest'];

const parts = [];
parts.push(`/* Auto-generated by compiler/web/build-core.js — 浏览器版编译核心（单一来源 = compiler/linux/lib） */
(function (g) {
  'use strict';
  var src = {};\n`);

for (const name of LIBS) {
  const text = fs.readFileSync(path.join(LINUX, name + '.js'), 'utf8');
  // 用 JSON.stringify 安全引号，避免模板/反引号/\${/反斜杠转义问题
  parts.push('  src[' + JSON.stringify(name) + '] = ' + JSON.stringify(text) + ';\n');
}

parts.push(`
  var factories = {};
  for (var k in src) (function (name) {
    factories[name] = new Function('module', 'exports', 'require', src[name]);
  })(k);
  var cache = {};
  function norm(s) {
    s = String(s);
    var i = s.indexOf('\\\\');
    while (i >= 0) { s = s.slice(0, i) + '/' + s.slice(i + 1); i = s.indexOf('\\\\'); }
    var j = s.lastIndexOf('/');
    if (j >= 0) s = s.slice(j + 1);
    if (s.slice(-3) === '.js') s = s.slice(0, -3);
    return s;
  }
  function require(s) {
    s = String(s);
    if (s.indexOf('babel.min.js') >= 0) {
      if (g.Babel) return g.Babel;
      throw new Error('web-core: vendor/babel.min.js 未加载');
    }
    if (s.indexOf('pako.min.js') >= 0) {
      if (g.pako) return g.pako;
      throw new Error('web-core: vendor/pako.min.js 未加载');
    }
    if (s.indexOf('jszip.min.js') >= 0 || s === 'jszip') {
      if (g.JSZip || g.jszip) return g.JSZip || g.jszip;
    }
    var name = norm(s);
    if (!factories[name]) throw new Error('web-core: 未知模块 ' + s);
    if (cache[name]) return cache[name].exports;
    var m = cache[name] = { i: name, l: false, exports: {} };
    factories[name](m, m.exports, require);
    m.l = true;
    return m.exports;
  }

  var hml = require('hml');
  var css = require('css');
  var bundle = require('bundle');
  var png = require('png2bin');
  var mf = require('manifest');

  g.CompilerCore = {
    render: {
      compileTemplate: hml.compileTemplate, parseHML: hml.parseHML,
      buildNode: hml.buildNode, Compiler: hml.Compiler, transformNode: hml.transformNode,
    },
    style: {
      compileCss: css.compileCss, splitTopLevel: css.splitTopLevel,
      parseDeclarationBlock: css.parseDeclarationBlock, normalizeValue: css.normalizeValue,
      expandShorthand: css.expandShorthand,
    },
    bundle: {
      bundlePage: bundle.bundlePage, bundleApp: bundle.bundleApp,
      babelToEs5: bundle.babelToEs5, initBabel: bundle.initBabel,
    },
    image: { pngToBin: png.pngToBin, decodePNG: png.decodePNG },
    manifest: { generateManifest: mf.generateManifest, stringify: mf.stringify },
    version: '1.0.0',
  };
})(typeof window !== 'undefined' ? window : globalThis);
`);

fs.writeFileSync(OUT_FILE, parts.join(''), 'utf8');
console.log('生成 ' + OUT_FILE + ' (' + parts.join('').length + ' B)');